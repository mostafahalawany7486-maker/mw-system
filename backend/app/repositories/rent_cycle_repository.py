from typing import Optional
from sqlalchemy import select, func
from sqlalchemy.orm import Session, selectinload
from app.repositories.base import BaseRepository
from app.models.rent_cycle import RentCycle, RentCycleRecord, RentCycleStatus
from app.models.rental import RentalContract
from app.models.property import Property


def _record_load_options():
    """Each full attribute chain, from RentCycle down — the same
    'repeat the whole path per option' pattern LeaseRepository.get_detail
    and RentalContractRepository.list_active_for_billing already use for
    their own nested eager-loads."""
    return (
        selectinload(RentCycle.records).selectinload(RentCycleRecord.rental_contract).selectinload(RentalContract.tenant),
        selectinload(RentCycle.records).selectinload(RentCycleRecord.rental_contract)
        .selectinload(RentalContract.property_ref).selectinload(Property.parent),
        selectinload(RentCycle.records).selectinload(RentCycleRecord.invoice),
        selectinload(RentCycle.records).selectinload(RentCycleRecord.installment),
    )


class RentCycleRepository(BaseRepository[RentCycle]):
    def __init__(self, db: Session):
        super().__init__(RentCycle, db)

    def get_detail(self, cycle_id: int) -> Optional[RentCycle]:
        stmt = (
            select(RentCycle)
            .options(*_record_load_options())
            .where(RentCycle.id == cycle_id, RentCycle.deleted_at.is_(None))
        )
        return self.db.execute(stmt).scalar_one_or_none()

    def get_by_period(self, year: int, month: int) -> Optional[RentCycle]:
        stmt = select(RentCycle).where(
            RentCycle.year == year, RentCycle.month == month, RentCycle.deleted_at.is_(None),
        )
        return self.db.execute(stmt).scalar_one_or_none()

    def next_cycle_number(self) -> str:
        stmt = select(func.count()).select_from(RentCycle)
        count = self.db.execute(stmt).scalar_one()
        return f"RC-{count + 1:06d}"

    def list_cycles(
        self, page: int, page_size: int, year: Optional[int], cycle_status: Optional[str],
        sort_by: Optional[str], sort_dir: str,
    ) -> tuple[list[RentCycle], int]:
        stmt = select(RentCycle).where(RentCycle.deleted_at.is_(None))
        if year:
            stmt = stmt.where(RentCycle.year == year)
        if cycle_status:
            stmt = stmt.where(RentCycle.cycle_status == cycle_status)

        count_stmt = select(func.count()).select_from(stmt.subquery())
        total = self.db.execute(count_stmt).scalar_one()

        if sort_by and hasattr(RentCycle, sort_by):
            column = getattr(RentCycle, sort_by)
            stmt = stmt.order_by(column.desc() if sort_dir == "desc" else column.asc())
        else:
            stmt = stmt.order_by(RentCycle.year.desc(), RentCycle.month.desc())

        stmt = stmt.offset((page - 1) * page_size).limit(page_size)
        items = list(self.db.execute(stmt).scalars().all())
        return items, total

    def dashboard_counts(self) -> dict:
        total = self.db.execute(select(func.count()).select_from(RentCycle)).scalar_one()
        open_cycles = self.db.execute(
            select(func.count()).select_from(RentCycle).where(
                RentCycle.cycle_status.notin_(list(RentCycleStatus.TERMINAL)), RentCycle.deleted_at.is_(None),
            )
        ).scalar_one()
        by_status_rows = self.db.execute(
            select(RentCycle.cycle_status, func.count()).where(RentCycle.deleted_at.is_(None)).group_by(RentCycle.cycle_status)
        ).all()
        return {
            "total_cycles": total,
            "open_cycles": open_cycles,
            "cycles_by_status": {status: count for status, count in by_status_rows},
        }


class RentCycleRecordRepository(BaseRepository[RentCycleRecord]):
    def __init__(self, db: Session):
        super().__init__(RentCycleRecord, db)

    def get_by_invoice_id(self, invoice_id: int) -> Optional[RentCycleRecord]:
        """Used by FinancialService.record_invoice_payment() to keep the
        old RentalPaymentInstallment schedule (still the source of truth
        for late-fee assessment — see RentalService.run_maintenance_sweep)
        in sync when an invoice generated by the same rent cycle gets
        paid through the newer Payment Engine instead of the old
        'Confirm Payment' flow. See docs/payment-collection-engine.md's
        'Unifying the two tenant-payment paths' section."""
        stmt = select(RentCycleRecord).where(RentCycleRecord.invoice_id == invoice_id, RentCycleRecord.deleted_at.is_(None)).limit(1)
        return self.db.execute(stmt).scalar_one_or_none()

    def list_for_cycle(self, cycle_id: int) -> list[RentCycleRecord]:
        stmt = (
            select(RentCycleRecord)
            .options(
                selectinload(RentCycleRecord.rental_contract).selectinload(RentalContract.tenant),
                selectinload(RentCycleRecord.rental_contract)
                .selectinload(RentalContract.property_ref).selectinload(Property.parent),
                selectinload(RentCycleRecord.invoice),
                selectinload(RentCycleRecord.installment),
            )
            .where(RentCycleRecord.cycle_id == cycle_id, RentCycleRecord.deleted_at.is_(None))
        )
        return list(self.db.execute(stmt).scalars().all())

    def existing_contract_ids_for_cycle(self, cycle_id: int) -> set[int]:
        stmt = select(RentCycleRecord.rental_contract_id).where(
            RentCycleRecord.cycle_id == cycle_id, RentCycleRecord.deleted_at.is_(None),
        )
        return set(self.db.execute(stmt).scalars().all())
